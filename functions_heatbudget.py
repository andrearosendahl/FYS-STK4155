    T_hflux = HFLUX_abs(fld) / determinator
    T_hflux.attrs[
        "long_name"
    ] = "Temperature contribution from Surface turbulent fluxes"
    T_hflux.attrs["standard_name"] = "HFLUX"
    T_hflux.attrs["units"] = "K"
    T_hstore = HSTOR_abs(fld, sigma) / determinator
    #T_hstore = Ts - (T_saf + T_cre + T_swcs + T_lwcs + T_hflux)
    T_hstore.attrs["long_name"] = "Temperature contribution from Ocean heat storage"
    T_hstore.attrs["standard_name"] = "HSTORE"
    T_hstore.attrs["units"] = "K"
    T_total = T_saf + T_cre + T_swcs + T_lwcs + T_hstore + T_hflux
    T_total.attrs["long_name"] = "Temperature contribution from all PCT contributions"
    T_total.attrs["standard_name"] = "dT_pct_sum"
    T_total.attrs["units"] = "K"
    return xr.merge(
        [
            Ts.to_dataset(name="dts"),
            T_saf.to_dataset(name="SAF"),
            T_cre.to_dataset(name="CRE"),
            T_swcs.to_dataset(name="SWCS"),
            T_lwcs.to_dataset(name="LWCS"),
            T_hstore.to_dataset(name="HSTORE"),
            T_hflux.to_dataset(name="HFLUX"),
            T_total.to_dataset(name="PTC_sum"),
        ]
    )