def read_atmos_data(
    model,
    first_year: int = 1,
    last_year: int = 10,
    path_to_data="/projects/NS9034K/CMIP6/",
) -> xr.Dataset:
    """
    Parameters
    ----------
    model :          python object, with experiment details as attributes (generated by class Modelinfo )
    varlist:         list, list of variable names which will be read and loaded into one xarray.Dataset
    realm:           str, Realm: e.g. Amon, AERmon, CFmon, Omon, SImon
    grid :           str, which grid resolution should be used.  e.g. 'gn', 'gr', 'gm', 'grz'
                     gn: native grid, 'gr': regridded somehow - not obvious
                     The grid is not really needed unless you want to specify one particular grid (out of several options)

    Returns
    -------
    ds_atm:          xarray.Dataset with the variables in varlist

    PLEASE NOTE that NorESM RAW cam.h0 files have incorrect time variable output, this is not the case for cmorized data

    """

    # noresm only provides rldscs at daily frequencies,
    # so need to upload that field seperately and
    # make monthly mean and then merge with the rest
    varlist = [
        "ts",
        "rsds",
        "rlus",
        "rsdscs",
        "rlds",
        "rsuscs",
        "hfls",
        "hfss",
    ]
    ds = read_noresm_cmor(
        model,
        varlist=varlist,
        realm="Amon",
        grid="gn",
        dim="time",
        transform_func=lambda ds: consistent_naming(ds),
        path_to_data=path_to_data,
    )
   
    ds2 = read_noresm_cmor(
        model,
        varlist=["rldscs"],
        realm="CFday",
        grid="gn",
        dim="time",
        transform_func=lambda ds: consistent_naming(ds),
        path_to_data=path_to_data,
    )
    
    ds2 = ds2["rldscs"].resample(time="1MS").mean()
    ds2 = ds2.assign_coords(time=ds.time)
    ds = xr.merge([ds, ds2])
    del ds2
    

    #ds = guf.fix_time(ds, yr0=ds.time.isel(time=0).dt.year.values)
    ds = ds.sel(time=slice("%i-01-01" % first_year, "%i-12-30" % last_year))

    # Net longwave flux at surface is not available as cmorized data.
    rlns = ds["rlus"] - ds["rlds"]
    rlns.attrs["long_name"] = "Net longwave flux at surface"
    rlns.attrs["units"] = "W m-2"
    rlns.attrs["standard_name"] = "net_longwave_flux_surface"
    # Clearsky net longwave flux at surface is not available as cmorized data.
    rlnscs = ds["rlus"] - ds["rldscs"]
    rlnscs.attrs["long_name"] = "Clear sky net longwave flux at surface"
    rlnscs.attrs["units"] = "W m-2"
    rlnscs.attrs["standard_name"] = "clearsky_net_longwave_flux_surface"

    ds = xr.merge([ds, rlns.to_dataset(name="rlns"), rlnscs.to_dataset(name="rlnscs")])
    return ds
    


def estimateQ(
    alpha: xr.DataArray,
    rsds: xr.DataArray,
    rlds: xr.DataArray,
    ts: xr.DataArray,
    hfls: xr.DataArray,
    hfss: xr.DataArray,
    rlns: xr.DataArray,
    sigma: float,
) -> xr.DataArray:
    """Q represents the storage of heat for all surface types (ocean, land) as well as oceanic transport
    The surface energy budget provides Q as a residual"""
    # rlns is defined as positive upwards, so a negative change (less positive values) increases Q
    #Q = (1 - alpha) * rsds + rlds - sigma * ts ** 4 - (hfls + hfss)
    Q = (1 - alpha) * rsds - rlns - (hfls + hfss)
    return Q


def SAF(changefld: xr.Dataset, basefld: xr.Dataset) -> xr.DataArray:
    """Surface albedo feedback temperature contribution
    Need to avoid inf and testing striktly greater than zero
    is not sufficient - use something very large as well, e.g 1e8
    """
    alb1cs = basefld.rsuscs / basefld.rsdscs
    alb1cs = xr.where((alb1cs > 0) & (alb1cs < 1e8), alb1cs, 0)
    alb2cs = changefld.rsuscs / changefld.rsdscs
    alb2cs = xr.where((alb2cs > 0) & (alb2cs < 1e8), alb2cs, 0)
    dalbcs = alb2cs - alb1cs
    return -dalbcs * changefld.rsds


def CRE(changefld: xr.Dataset, basefld: xr.Dataset) -> xr.DataArray:
    """Cloud temperature effect temperature contribution
    assumptions:
    1) zero difference in longwave upwelling surface radiation,
    because the radiation emitted from the surface is not directly a function of cluds (~sigma*T^4)
    2) albedo_mean = unperturbed mean climate state, controls the influence of surface albedo on CRE
    since the effect of surface albedo changes is treated in SAF
    rlus = rluscs = rluscld
    rlus = rlds + rlns
    rlnscld = rlns - rlnscs
    rldscld = rlds - rldscs
    rldscs = rlus - rlnscs => rldscs =  rlds + rlns - rlnscs
    rldscld = rlds - rldscs = rlds - (rlds + rlns - rlnscs) = rlnscs - rlns

    Need to avoid inf and testing striktly greater than zero
    is not sufficient - use something very large as well, e.g 1e8
    """
    cre_sw = (changefld.rsds - changefld.rsdscs) - (basefld.rsds - basefld.rsdscs)
    # d_lw_change = changefld.rlnscs - changefld.rlns
    # d_lw_base = basefld.rlnscs - basefld.rlns
    # cre_lw = d_lw_change - d_lw_base
    cre_lw = changefld.rlds - changefld.rldscs - (basefld.rlds - basefld.rldscs)
    albedo_mean = basefld.rsuscs / basefld.rsdscs
    albedo_mean = xr.where((albedo_mean > 0) & (albedo_mean < 1e8), albedo_mean, 0)
    # return (1 - albedo_mean) * cre_sw + cre_lw
    return (1 - albedo_mean) * cre_sw + cre_lw


def SWCS(changefld: xr.Dataset, basefld: xr.Dataset) -> xr.DataArray:
    """Non-SAF (surface albedo feedback) shortwave clear-sky feedback temperature contribution
    Need to avoid inf and testing striktly greater than zero
    is not sufficient - use something very large as well, e.g 1e8
    """
    albedo_mean = basefld.rsuscs / basefld.rsdscs
    albedo_mean = xr.where((albedo_mean > 0) & (albedo_mean < 1e8), albedo_mean, 0)
    dsw_cs = changefld.rsdscs - basefld.rsdscs
    return (1 - albedo_mean) * dsw_cs


def LWCS(changefld: xr.Dataset, basefld: xr.Dataset) -> xr.DataArray:
    """Longwave clear-sky feedbacks temperature contribution
    Assume that the emitted radiation from the surface is not directly a function of clouds (~sigma*T^4): rsus = rsuscs
    then:
    rlus = rluscs
    rlds + rlns = rlus
    rlnscs = rluscs - rldscs = rlus - rldscs
    -> rldscs = rlus - rlnscs = rlds + rlns -rlnscs"""
    # rldscs_base = basefld.rlds + basefld.rlns - basefld.rlnscs
    # rldscs_change = changefld.rlds + changefld.rlns - changefld.rlnscs
    # return rldscs_change - rldscs_base
    return changefld.rldscs - basefld.rldscs


def HSTOR(changefld: xr.Dataset, basefld: xr.Dataset, sigma: float) -> xr.DataArray:
    """Ocean heat storage temperature contribution
    possible to split this into storage and transport terms
    Need to avoid inf and testing striktly greater than zero
    is not sufficient - use something very large as well, e.g 1e8
    """
    alpha_base = basefld.rsuscs / basefld.rsdscs
    alpha_base = xr.where((alpha_base > 0) & (alpha_base < 1e8), alpha_base, 0)
    Qbase = estimateQ(
        alpha_base,
        basefld.rsds,
        basefld.rlds,
        basefld.ts,
        basefld.hfls,
        basefld.hfss,
        basefld.rlns,
        sigma,
    )
    alpha_change = changefld.rsuscs / changefld.rsdscs
    alpha_change = xr.where((alpha_change > 0) & (alpha_change < 1e8), alpha_change, 0)
    Qchange = estimateQ(
        alpha_change,
        changefld.rsds,
        changefld.rlds,
        changefld.ts,
        changefld.hfls,
        changefld.hfss,
        changefld.rlns,
        sigma,
    )
    return -(Qchange - Qbase)


def HFLUX(changefld: xr.Dataset, basefld: xr.Dataset) -> xr.DataArray:
    """Surface turbulent fluxes temperature contribution
    hfls : latent heat
    hfss : sensible heat
    """
    dhfls = changefld.hfls - basefld.hfls
    dhfss = changefld.hfss - basefld.hfss
    return -(dhfss + dhfls)


def partial_temperature_contributions(
    changefld: xr.Dataset,
    basefld: xr.Dataset,
    sigma: float = 5.67e-8,
) -> xr.Dataset:
    """Each term represents a partial temperature contribution for SAF, CRE,
    changes in shortwave clear-sky radiation unrelated to SAF,
    changes in longwave clear-sky radiation, changes in heat storage,
    and changes in surface turbulent fluxes.
    Each PTC represents the temperature contribution of the corresponding feedback to the total Arctic temperature change
    """
    determinator = 4 * sigma * (basefld.ts ** 3)
    dTs = changefld.ts - basefld.ts
    dTs.attrs["long_name"] = "Change in surface skin temperature"
    dTs.attrs["standard_name"] = "ts"
    dTs.attrs["units"] = "K"
    dT_saf = SAF(changefld, basefld) / determinator
    dT_saf.attrs["long_name"] = "Temperature contribution from Surface albedo feedback"
    dT_saf.attrs["standard_name"] = "SAF"
    dT_saf.attrs["units"] = "K"
    dT_cre = CRE(changefld, basefld) / determinator
    dT_cre.attrs["long_name"] = "Temperature contribution from Cloud radiative effect"
    dT_cre.attrs["standard_name"] = "CRE"
    dT_cre.attrs["units"] = "K"
    dT_swcs = SWCS(changefld, basefld) / determinator
    dT_swcs.attrs[
        "long_name"
    ] = "Temperature contribution from Shortwave clear-sky feedback"
    dT_swcs.attrs["standard_name"] = "SWCS"
    dT_swcs.attrs["units"] = "K"
    dT_lwcs = LWCS(changefld, basefld) / determinator
    dT_lwcs.attrs[
        "long_name"
    ] = "Temperature contribution from Longwave clear-sky feedback"
    dT_lwcs.attrs["standard_name"] = "LWCS"
    dT_lwcs.attrs["units"] = "K"
    dT_hflux = HFLUX(changefld, basefld) / determinator
    dT_hflux.attrs[
        "long_name"
    ] = "Temperature contribution from Surface turbulent fluxes"
    dT_hflux.attrs["standard_name"] = "HFLUX"
    dT_hflux.attrs["units"] = "K"
    dT_hstore = HSTOR(changefld, basefld, sigma) / determinator
    #dT_hstore = dTs - (dT_saf + dT_cre + dT_swcs + dT_lwcs + dT_hflux)
    dT_hstore.attrs["long_name"] = "Temperature contribution from Ocean heat storage"
    dT_hstore.attrs["standard_name"] = "HSTORE"
    dT_hstore.attrs["units"] = "K"
    dT_total = dT_saf + dT_cre + dT_swcs + dT_lwcs + dT_hstore + dT_hflux
    dT_total.attrs["long_name"] = "Temperature contribution from all PCT contributions"
    dT_total.attrs["standard_name"] = "dT_pct_sum"
    dT_total.attrs["units"] = "K"
    return xr.merge(
        [
            dTs.to_dataset(name="dts"),
            dT_saf.to_dataset(name="SAF"),
            dT_cre.to_dataset(name="CRE"),
            dT_swcs.to_dataset(name="SWCS"),
            dT_lwcs.to_dataset(name="LWCS"),
            dT_hstore.to_dataset(name="HSTORE"),
            dT_hflux.to_dataset(name="HFLUX"),
            dT_total.to_dataset(name="PTC_sum"),
        ]
    )


def amplfication_factor(
    changefld: xr.Dataset,
    basefld: xr.Dataset,
    latlim: int or float,
    ) -> xr.Dataset:
    """
    Amplification factor: the ratio between the temperature change defined by latlim 
    and the global temperature change

    Parameters
    ----------
    changefld : xarray.Dataset with the perturbed state (e.g. SSPs) temperature
    basefld : xarray.Dataset with the base state (control) temperature
    latlim : int or float, latitude limit used to calculate the amplification factor
    Returns
    -------
    ds : xarray.Dataset with the amplification factor defined 
    """
    # import workingfolder.general_util_funcs as guf
    if 'tas' in list(changefld.keys()):
        dts = changefld.dtas - basefld.tas
        varname = 'tas'
    else:
        dts = changefld.dts - basefld.ts
        varname = 'ts'
    dtsgm = global_avg(dts)
    if latlim > 0:
        dtsreg = global_avg(dts.sel(lat=slice(latlim, None)))
    else :
        dtsreg = global_avg(dts.sel(lat=slice(-90, latlim)))
    aafac = dtsreg/dtsgm
    aafac.attrs["long_name"] = "Amplification factor"
    aafac.attrs["description"] = "Amplification factor calculated from %s, latitude limit %.1f"%(varname, latlim)
    aafac.attrs["standard_name"] = "amplification_factor"
    aafac.attrs["units"] = "K K^-1"
    return aafac.to_dataset(name = 'aafac')



class Modelinfo:
    """
    Sets the details of the model experiment
    """

    def __init__(
        self,
        name="NorESM2-LM",
        institute="NCC",
        activity_id="CMIP",
        expid="piControl",
        realiz=["r1i1p1f1"],
        branchtime_year=0,
    ):
        """
        The attributes need to be general and not file specific thus detail like Amon, grid label should not be included

        Attributes
        ----------
        name :        str, name of the CMIP model - typically the Source ID
        institute :   str, Institution ID
        activity_id:  str, activity ID for experiment
        expid :       str, Experiment ID, e.g. piControl, abrupt-4xCO2
        realiz :      str, variant labels saying something about which realization (ensemble member), initial conditions, forcings etc.
                      e.g. 'r1i1p1f1'
        branchtime_year : int, when simulation was branched off from parent.
                          Useful when anomalies are considered e.g. abrupt-4xCO2, historical
                          then you only consider data from piControl for the corresponding period
                          e.g. xarray.DataArray(year = slice(model.branchtime_year,None))

        """
        self.name = name
        self.institute = institute
        self.activity_id = activity_id
        self.expid = expid
        self.realiz = realiz
        self.branchtime_year = branchtime_year





